// Prefijo usado para distinguir un ícono Tabler de un emoji/texto libre en
// campos que aceptan ambos (ver `iconPickerField` en components.jsx).
export const TABLER_PREFIX = 'tabler:';

export function isTablerIconValue(value) {
  return typeof value === 'string' && value.startsWith(TABLER_PREFIX);
}

export function getTablerIconComponent(value) {
  if (!isTablerIconValue(value)) return null;
  return TABLER_ICONS[value.slice(TABLER_PREFIX.length)] || null;
}
