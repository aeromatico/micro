<details style="margin:10px 0 0;max-width:900px"><summary style="cursor:pointer"><strong>¿Qué es una orden?</strong></summary>
<div class="text-muted" style="padding:6px 0">
 <p>Una <strong>orden</strong> es una compra: agrupa lo que pidió una persona (por ejemplo 2 General + 1 VIP), con sus precios y su comprador. <strong>Una orden no reserva lugares</strong>: las entradas se emiten cuando la orden se confirma.</p>
 <ul>
  <li><strong>Pendiente de pago</strong> — el comprador aún no pagó. No tiene entradas.</li>
  <li><strong>En verificación</strong> — el comprador avisó que pagó (o espera tu aprobación). <em>Te toca a ti</em>: verifica tu banco y confirma el cobro.</li>
  <li><strong>Confirmada</strong> — cobrada; las entradas ya se emitieron y se enviaron.</li>
  <li><strong>En incidencia</strong> — el pago tiene un problema (monto, comprobante…). Resuélvelo o cancela.</li>
  <li><strong>Vencida</strong> — nadie pagó en 72 h; se da por abandonada. <strong>Cancelada</strong> — anulada.</li>
 </ul>
 <p>Las entradas gratuitas se confirman solas, sin pasar por aquí. El detalle de cada orden te dice qué hacer.</p>
</div></details>
